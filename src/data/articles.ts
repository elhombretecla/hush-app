/** Builds body blocks with stable ids ("<article>-<n>"). Append new blocks only at the end. */
function body(articleId: string, blocks: [BlockType, string][]): ContentBlock[] {
  return blocks.map(([type, text], i) => ({ id: `${articleId}-${i + 1}`, type, text }));
}

